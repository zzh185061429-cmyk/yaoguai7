/**
 * 递归收集某个节点及其所有子节点的扁平列表
 */
export function flattenLocations(nodes: LocationNode[], parentPath: string = ''): (LocationNode & { fullPath: string })[] {
  const result: (LocationNode & { fullPath: string })[] = [];

  for (const node of nodes) {
    const fullPath = parentPath ? `${parentPath} ❯ ${node.name}` : node.name;
    result.push({ ...node, fullPath });
    if (node.children && node.children.length > 0) {
      result.push(...flattenLocations(node.children, fullPath));
    }
  }

  return result;
}

/**
 * 获取指定地域中所有地点的平铺列表
 */
export function getAllLocationsInRegion(region: RealmRegion) {
  return flattenLocations(region.roots, region.name);
}

/**
 * 递归寻找节点以及其祖先路径
 */
export function findLocationWithAncestors(nodes: LocationNode[], targetId: string, ancestors: LocationNode[] = []): { node: LocationNode; path: LocationNode[] } | null {
  for (const node of nodes) {
    const currentPath = [...ancestors, node];
    if (node.id === targetId) {
      return { node, path: currentPath };
    }
    if (node.children && node.children.length > 0) {
      const found = findLocationWithAncestors(node.children, targetId, currentPath);
      if (found) return found;
    }
  }
  return null;
}
